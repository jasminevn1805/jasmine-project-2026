interface RecipeStore {
  recipes: Recipe[]
  seeded: boolean
  addRecipe: (recipe: Recipe) => void
  updateRecipe: (id: string, updates: Partial<Recipe>) => void
  removeRecipe: (id: string) => void
  reassignCategory: (fromId: string, toId: string) => void
  getRecipeById: (id: string) => Recipe | undefined
  seedRecipes: () => void
}

export const useRecipeStore = create<RecipeStore>()(
  persist(
    (set, get) => ({
      recipes: [],
      seeded: false,

      seedRecipes: () => {
        if (get().seeded) return
        set({ recipes: SEED_RECIPES, seeded: true })
      },

      addRecipe: (recipe) =>
        set((state) => ({ recipes: [recipe, ...state.recipes] })),

      updateRecipe: (id, updates) =>
        set((state) => ({
          recipes: state.recipes.map((r) =>
            r.id === id ? { ...r, ...updates } : r
          ),
        })),

      removeRecipe: (id) =>
        set((state) => ({
          recipes: state.recipes.filter((r) => r.id !== id),
        })),

      reassignCategory: (fromId, toId) =>
        set((state) => ({
          recipes: state.recipes.map((r) =>
            r.category === fromId ? { ...r, category: toId } : r
          ),
        })),

      getRecipeById: (id) => get().recipes.find((r) => r.id === id),
    }),
    { 
      name: 'cookstash-recipes',
      version: 5,
      migrate: (persisted: unknown, version: number) => {
        if (version < 5) {
          const state = persisted as { recipes: Recipe[]; seeded: boolean }
          // Rename category 'other' → 'unsorted' for existing recipes
          const recipes = (state.recipes ?? []).map((r) =>
            r.category === 'other' ? { ...r, category: 'unsorted' } : r
          )
          return { ...state, recipes }
        }
        return persisted
      },
    }
  )
)
