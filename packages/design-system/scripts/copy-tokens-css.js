#!/usr/bin/env node

/**
 * Post-build: generate dist/tokens.css
 *
 * Vite's library mode bundles from a single JS entry point, so CSS-only files
 * aren't automatically included. This script inlines variables.css directly
 * into dist/tokens.css so the output is fully self-contained.
 *
 * tokens.css contains only CSS custom properties (no reset, no global styles)
 * and is the correct import for projects that use Tailwind or another framework.
 *
 * Imported via package.json exports:
 *   "@jasmine/design-system/tokens" → "./dist/tokens.css"
 */

const fs = require('fs');
const path = require('path');

const variablesSrc = path.join(__dirname, '../src/styles/variables.css');
const dest = path.join(__dirname, '../dist/tokens.css');

const variablesContent = fs.readFileSync(variablesSrc, 'utf-8');

const output = `/**
 * Jasmine Design System — Token Variables Only
 * Auto-generated by scripts/copy-tokens-css.js
 *
 * USE THIS in projects with Tailwind or another CSS framework.
 * Contains only CSS custom properties — no reset, no global styles.
 *
 * Import in your project:
 *   @import '@jasmine/design-system/tokens';
 *
 * Use '@jasmine/design-system/styles' only in Storybook / non-Tailwind contexts.
 */

${variablesContent}`;

fs.writeFileSync(dest, output, 'utf-8');
console.log('✅ Generated dist/tokens.css (variables only)');
